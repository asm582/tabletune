"""T4 / A10G / H100 side by side: the same studies, metrics computed the same way.
The worst-loss matrix and the controller results.
Writes experiments/results/h100-studies/comparison/COMPARISON.md and comparison_long.csv (every config x load x GPU, mean/min/max over runs)."""
import csv, glob, os, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import STUDIES, SWEEPS  # noqa: E402
OLD = NEW = V2 = SWEEPS
HERE = os.path.join(STUDIES, "comparison")
os.makedirs(HERE, exist_ok=True)
def root(gpu): return {"H100": NEW, "H100 V2": V2}.get(gpu, OLD)
def load(gpu, sweep):
    d = {}; n = 0
    for p in [f"{root(gpu)}/{sweep}"] + sorted(glob.glob(f"{root(gpu)}/{sweep}-r[0-9]")):
        f = f"{p}/summary.csv"
        if not os.path.exists(f): continue
        n += 1
        for r in csv.DictReader(open(f)):
            if r["tok_s_gpu"]: d.setdefault((r["config"], int(r["concurrency"])), []).append(float(r["tok_s_gpu"]))
    return d, n
def merge(*ds):
    out = {}
    for d in ds:
        for k, v in d.items(): out.setdefault(k, v)
    return out
m = lambda v: st.mean(v)
# study: per GPU -> (sweeps to merge, tuned config, fixed configs, nospec source sweep)
STUDIES = {
 "EAGLE-3, Qwen3-4B, code (T=1.0)": {
   "T4": (["code128t-t4"], "dsd-tuned-v3"), "A10G": (["code128t-a10g"], "eagle-tuned"), "H100": (["code128t-h100"], "eagle-tuned"),
   "fixed": ["k1", "k2", "k3"], "nospec": "nospec"},
 "EAGLE-3, Qwen3-4B-AWQ (4-bit)": {
   "T4": (["code128t-t4-awq"], "eagle-tuned"), "H100": (["code128t-h100-awq"], "eagle-tuned"),
   "fixed": ["k1", "k2", "k3"], "nospec": "nospec"},
 "n-gram, code-apply (greedy)": {
   "T4": (["ngram-apply-t4", "ngram-apply-t4-v2"], "ngram-tuned-v2"), "H100": (["ngram-apply-h100", "ngram-apply-h100-v2"], "ngram-tuned-v2"),
   "fixed": ["ngram-k1", "ngram-k3", "ngram-k5"], "nospec": "nospec"},
 "Qwen3-0.6B draft model, code": {
   "T4": (["draft-code-t4", "code128t-t4"], "draft-tuned"), "H100": (["draft-code-h100", "code128t-h100"], "draft-tuned"),
   "fixed": ["draft-k1", "draft-k3", "draft-k5"], "nospec": "nospec"},
 "DFlash, code": {
   "A10G": (["dflash-code-a10g", "code128t-a10g"], "dflash-tuned"), "H100": (["dflash-code-h100", "code128t-h100"], "dflash-tuned"),
   "fixed": ["dflash-k1", "dflash-k3", "dflash-k8"], "nospec": "nospec"},
 "EAGLE-3, Spec-Bench chat (greedy, loads 1-64)": {
   "T4": (["baseline-t4", "dsd-t4"], "dsd-tuned-v2"), "H100": (["baseline-h100", "dsd-h100"], "eagle-tuned"),
   "fixed": ["k1", "k2", "k3"], "nospec": "nospec", "docs": "dsd-docs"},
}
GPUS = ["T4", "A10G", "H100", "H100 V2"]
# H100 V2 (vLLM nightly 43b4aaea, V2 runner, full CUDA graphs per draft length): the H100 studies with h100v2 names
for cfg in STUDIES.values():
    if "H100" in cfg:
        sw, tuned = cfg["H100"]; cfg["H100 V2"] = ([x.replace("h100", "h100v2") for x in sw], tuned)
STUDIES["EAGLE-3, Qwen3-4B-AWQ, table restricted to lengths 0/1/3 (V2 only)"] = {
    "H100 V2": (["code128t-h100v2-awq-k013", "code128t-h100v2-awq"], "eagle-tuned"), "fixed": ["k1", "k2", "k3"], "nospec": "nospec"}
lines = ["# T4 / A10G / H100 comparison", "",
 "H100: isolated runs (one pod per otherwise idle node), as the T4/A10G ran alone on their hosts, on vLLM 353e491ef with the V1 runner like the T4/A10G. H100 V2: the same studies on vLLM nightly 43b4aaea with the V2 runner (full CUDA graphs per draft length). Every study ran on each GPU with the same pipeline script, prompts, loads (1-128; Spec-Bench 1-64), batch cap (128; Spec-Bench 64) and vLLM V1 runner. Throughput: output tokens/s per GPU, mean of the runs listed. Losses are against the best fixed draft length at each load (\"best fixed\"). Generated by `compare_gpus.py`.", ""]
longrows = []
summ = ["| Study | GPU | Runs | Tuned table | Best single fixed (worst loss) | Tuned worst loss | incl. no spec | Tuned vs mean-best, 1-64 / 96-128 | Tuned vs no spec, 1 / max load |", "|---|---|---|---|---|---|---|---|---|"]
detail = []
for study, cfg in STUDIES.items():
    detail += [f"## {study}", ""]
    for gpu in GPUS:
        if gpu not in cfg: continue
        sweeps, tuned = cfg[gpu]
        parts = [load(gpu, s) for s in sweeps]; D = merge(*[p[0] for p in parts]); runs = parts[0][1]
        C = sorted({c for (k, c) in D if k == tuned})
        fx = [k for k in cfg["fixed"] if all((k, c) in D for c in C)]
        best = {c: max(m(D[(k, c)]) for k in fx) for c in C}
        L = lambda k, c: 100 * (1 - m(D[(k, c)]) / best[c])
        worst = {k: max(L(k, c) for c in C) for k in fx}
        bs = min(worst, key=worst.get); mb = min(fx, key=lambda k: st.mean(L(k, c) for c in C))
        tw = max(L(tuned, c) for c in C); twc = max(C, key=lambda c: L(tuned, c))
        ns = cfg["nospec"]
        incl = max(100 * (1 - m(D[(tuned, c)]) / max(best[c], m(D[(ns, c)]) if (ns, c) in D else 0)) for c in C)
        lo = [c for c in C if c <= 64]; hi = [c for c in C if c >= 96]
        g = lambda cs: 100 * st.mean(m(D[(tuned, c)]) / m(D[(mb, c)]) - 1 for c in cs) if cs else float("nan")
        vns = lambda c: 100 * (m(D[(tuned, c)]) / m(D[(ns, c)]) - 1) if (ns, c) in D else float("nan")
        tab = f"`{open(glob.glob(f'{root(gpu)}/../{[s for s in sweeps][0]}')[0]).read() if False else ''}`"
        summ.append(f"| {study} | {gpu} | {runs} | {tuned} | {bs}: {worst[bs]:.1f}% | **{tw:.1f}%** ({twc} req.) | {incl:.1f}% | {mb}: {g(lo):+.1f}% / {g(hi):+.1f}% | {vns(C[0]):+.0f}% / {vns(C[-1]):+.0f}% |")
        cols = ([ns] if any((ns, c) in D for c in C) else []) + fx + [tuned] + ([cfg["docs"]] if "docs" in cfg else [])
        detail += [f"**{gpu}** ({runs} runs; tuned table = `{tuned}`)", "", "| Load | " + " | ".join(cols) + " | tuned loss vs best fixed |", "|" + "---|" * (len(cols) + 2)]
        for c in C:
            detail.append(f"| {c} | " + " | ".join(f"{m(D[(k, c)]):,.0f}" if (k, c) in D else "-" for k in cols) + f" | {L(tuned, c):+.1f}% |")
            for k in cols:
                if (k, c) in D: longrows.append([study, gpu, k, c, round(m(D[(k, c)]), 1), round(min(D[(k, c)]), 1), round(max(D[(k, c)]), 1), len(D[(k, c)])])
        detail.append("")
# controller studies: gain of controller-on over the same table controller-off, per load
CTRL = [
 ("Controller from the docs table (EAGLE-3, mismatched chat prior)", {"T4": ("ctrlval-refit", "ctrlval-off"), "A10G": ("ctrlval-refit-a10g", "ctrlval-off-a10g"), "H100": ("ctrlval-refit-h100", "ctrlval-off-h100")}, "dsd-docs"),
 ("Controller from the docs table / 4 (stress table)", {"T4": ("ctrlval-refit", "ctrlval-off"), "A10G": ("ctrlval-refit-a10g", "ctrlval-off-a10g"), "H100": ("ctrlval-refit-h100", "ctrlval-off-h100")}, "dsd-rescaled"),
 ("Controller, 4-bit AWQ target, docs table", {"T4": ("ctrlval-refit-t4-awq", "ctrlval-off-t4-awq"), "H100": ("ctrlval-refit-h100-awq", "ctrlval-off-h100-awq")}, "dsd-docs"),
 ("Controller, n-gram from an untuned table (calibrated prior)", {"T4": ("ngram-ctrl-calib", "ngram-ctrl-off"), "H100": ("ngram-ctrl-calib-h100", "ngram-ctrl-off-h100")}, "ngram-untuned"),
 ("Controller, n-gram from an untuned table (EAGLE-3's prior)", {"T4": ("ngram-ctrl-eagleprior", "ngram-ctrl-off"), "H100": ("ngram-ctrl-eagleprior-h100", "ngram-ctrl-off-h100")}, "ngram-untuned"),
 ("Controller, draft model from the T4 EAGLE-3 table", {"T4": ("draft-ctrl-v3table", "draft-ctrl-off"), "H100": ("draft-ctrl-v3table-h100", "draft-ctrl-off-h100")}, "draft-v3table"),
 ("Controller, DFlash from the T4 EAGLE-3 table (any-length mode)", {"A10G": ("dflash-ctrl-v3table-a10g", "dflash-ctrl-off-a10g"), "H100": ("dflash-ctrl-v3table-h100", "dflash-ctrl-off-h100")}, "dflash-v3table"),
]
for _, per, _ in CTRL:
    if "H100" in per: per["H100 V2"] = tuple(x.replace("h100", "h100v2") for x in per["H100"])
ctl = ["| Controller study | GPU | Runs | Gain per load (controller on vs off, same table) |", "|---|---|---|---|"]
for name, per, cfgname in CTRL:
    for gpu in GPUS:
        if gpu not in per: continue
        on, n1 = load(gpu, per[gpu][0]); off, n2 = load(gpu, per[gpu][1])
        C = sorted({c for (k, c) in on if k == cfgname and (k, c) in off})
        if not C: continue
        ctl.append(f"| {name} | {gpu} | {min(n1, n2)} | " + ", ".join(f"{c}: {100*(m(on[(cfgname,c)])/m(off[(cfgname,c)])-1):+.1f}%" for c in C) + " |")
        for c in C:
            longrows.append([name, gpu, cfgname + " (controller on)", c, round(m(on[(cfgname, c)]), 1), round(min(on[(cfgname, c)]), 1), round(max(on[(cfgname, c)]), 1), len(on[(cfgname, c)])])
            longrows.append([name, gpu, cfgname + " (controller off)", c, round(m(off[(cfgname, c)]), 1), round(min(off[(cfgname, c)]), 1), round(max(off[(cfgname, c)]), 1), len(off[(cfgname, c)])])
lines += ["## Summary: tuned tables against fixed lengths", ""] + summ + ["", "## Summary: the controller", ""] + ctl + [""] + detail
open(f"{HERE}/COMPARISON.md", "w").write("\n".join(lines) + "\n")
with open(f"{HERE}/comparison_long.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["study", "gpu", "config", "concurrency", "tok_s_gpu_mean", "min", "max", "runs"]); w.writerows(longrows)
print("\n".join(summ)); print(); print("\n".join(ctl))
